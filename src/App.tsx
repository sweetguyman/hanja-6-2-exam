function synthBan(used: Set<string>): Q {
  const overlap = (a: string, b: string): boolean => a.includes(b.charAt(0)) || a.includes(b.charAt(1));
  const chosen: string[] = [];
  for (const p of shuffle(BAN_V)) {
    if (used.has(pairKey(p))) continue;
    if (chosen.some((c: string) => overlap(c, p))) continue;
    chosen.push(p);
    if (chosen.length === 3) break;
  }
  const inv = shuffle(BAN_I).find((p: string) => !used.has(pairKey(p)) && !chosen.some((c: string) => overlap(c, p))) ?? BAN_I[0];
  const all = shuffle(chosen.concat([inv]));
  all.forEach((p: string) => used.add(pairKey(p)));
  return { k: "ban", p: all, ans: String(all.indexOf(inv) + 1) };
}

