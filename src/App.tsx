function pick<T extends { id: string }>(pool: T[], n: number, kind: string, rec: Record<string, string[]>): T[] {
  const list = rec[kind] ?? [];
  const pos = new Map<string, number>();
  list.forEach((id: string, i: number) => pos.set(id, i));
  const fresh = shuffle(pool.filter((x: T) => !pos.has(x.id)));
  const old = pool.filter((x: T) => pos.has(x.id)).sort((x: T, y: T) => (pos.get(x.id) ?? 0) - (pos.get(y.id) ?? 0));
  const chosen = fresh.concat(old).slice(0, n);
  const ids = new Set(chosen.map((c: T) => c.id));
  const cap = Math.max(n, Math.floor(pool.length * 0.8));
  rec[kind] = list.filter((id: string) => !ids.has(id)).concat(chosen.map((c: T) => c.id)).slice(-cap);
  return shuffle(chosen);
}

