const norm = (s: string): string => s.replace(/[\s().:ː·\-~,]/g, "");
function isCorrect(q: Q, v: string, self: string | undefined): boolean {
  if (q.k === "dok") return v.trim() !== "" && norm(v) === norm(q.ans);
  if (q.k === "hun") {
    const h = HMAP[q.c ?? ""];
    if (!h) return false;
    return v.split(/[\/|]/).some((part: string) => part.trim() !== "" && h.acc.some((a: string) => norm(a) === norm(part)));
  }
  if (q.k === "ssg") return (v.trim() !== "" && norm(v) === q.ans) || self === "O";
  return v === q.ans;
}
const charExpl = (w: string): string =>
  w.split("").map((c: string) => (HMAP[c] ? `${c}(${HMAP[c].acc[0]})` : c)).join(" + ");
function wanWord(q: Q): string {
  const s = q.s ?? "";
  const i = s.indexOf("( )");
  const opt = (q.o ?? [])[Number(q.ans) - 1] ?? "";
  const after = s.charAt(i + 3);
  const before = i > 0 ? s.charAt(i - 1) : "";
  if (/[\u4e00-\u9fff]/.test(after)) return opt + after;
  if (/[\u4e00-\u9fff]/.test(before)) return before + opt;
  return opt;
}
